// 485发送轮询线程：负责从全局Tx取帧发送、延时200ms等待接收
class Rs485SendPollThread : public QThread
{
public:
    std::atomic<bool> m_running{false};
    SerialPort* m_ctrl = nullptr;

    void SetCtrl(SerialPort* p) { m_ctrl = p; }
    void StartPoll()
    {
        m_running = true;
        start();
    }
    void StopPoll()
    {
        m_running = false;
        Rs485BufferMgr::GetInstance()->WakeAll();
        if (!wait(500))
        {
            terminate();
            wait();
        }
    }

protected:
    void run() override;
};
